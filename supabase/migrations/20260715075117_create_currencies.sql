CREATE TABLE public.currencies (
	iso_code CHAR(3) PRIMARY KEY,
	iso_numeric CHAR(3) NOT NULL,
	name TEXT NOT NULL,
	symbol VARCHAR(10) NOT NULL,
	start_date DATE NOT NULL,
	is_default BOOLEAN DEFAULT FALSE NOT NULL,
	is_enabled BOOLEAN DEFAULT TRUE NOT NULL,
    sort_order INT DEFAULT 999 NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.currencies ENABLE ROW LEVEL SECURITY;

CREATE TRIGGER set_updated_at_currencies
  BEFORE UPDATE ON public.currencies
  FOR EACH ROW EXECUTE FUNCTION extensions.moddatetime(updated_at);

CREATE POLICY "Allow read-only access to all users" 
    ON public.currencies FOR SELECT TO anon, authenticated USING (true);

